"""Decode sets (`evalsuite run --decode`): IFEval 100, HumanEval+ 60, math 50 (MATH-500 L3-5 + GSM8K), RULER-style
24 at EVALSUITE_RULER_TOKENS, generated by one variant with the deployed semantics of decode-only variants (exact
prefill, tiers at decode). Default: non-thinking chat template, greedy (deterministic; MoonShots' GSM8K setting), so
two same-weights runs differ only through numerics (the floor's stock combine order). --thinking: thinking mode with
Qwen's sampler (T 0.6, top-p 0.95, top-k 20) and a per-item seed shared by every variant (paired sampling).
Rows are appended to results/<V>/decode[_think].jsonl as they finish (resumable)."""
from __future__ import annotations
import ctypes, hashlib, json, os, sys, time
from . import env
from . import model as M, data as D

SETS = ("math", "ifeval", "humaneval", "ruler", "mgsm", "multi", "agent")   # multi / agent: no gold (decode_report.AGREE)
CARD = ("ifbench", "gpqad", "lcb6")   # the card benchmarks: decoded only when --sets names them
THINK_CAP = {"math": 6144, "ifeval": 4096, "humaneval": 4096, "ruler": 2048}


def path(name, thinking):
    return os.path.join(env.ROOT, "results", name, "decode_think.jsonl" if thinking else "decode.jsonl")


EOS = {248044, 248046}


def _gen(rt, ids, cap, sampler, seed):
    from mtplx import generation as G
    res = G.generate_ar(rt, list(ids), max_tokens=cap, sampler=sampler, seed=seed)
    toks = [int(x) for x in (getattr(res, "tokens", None) or [])]
    for j, x in enumerate(toks):
        if x in EOS:
            return toks[:j + 1], "eos"
    return toks, "length"


def _gen_mtp(rt, ids, cap, sampler, seed):
    """Breakthrough's small-RAM configs as they ship (bt_b12, MTP runtime): the release prefill (D1i: attention in
    512-token query chunks, the MoE once per 4096 tokens; bt_b12.b12_prefill_state), then MTP speculative decoding,
    spec125 3:3:0 (k_mtp 3, max_draft 3, no lookup), greedy, stopping at EOS, as bt_b12.py's spec / GSM-MTP paths run it"""
    assert sampler.temperature == 0.0, "the MTP rows are greedy only"
    import bt_b12 as B, spec125
    from bigmoe_v3f.fuse import reset_generation_state
    from bigmoe_v3f.gated import ext
    model = rt.model
    reset_generation_state(model)                 # (spec125's own reset imports ~/BigMoE's bigmoe: BIGMOE_RESET_GEN=0)
    B.STASH.clear(); B.PENDH.clear()
    aw0, pf0, t0 = B.AW_N[0], len(B.PFR_LOG), time.perf_counter()   # B12_FOLD: ALLWAIT layer calls, PFR releases
    state = B.b12_prefill_state(model, list(ids), 512, 4096)
    t1 = time.perf_counter()
    m0, d0, k0 = ext.stats()["misses"], ext.defer_stats(), diskread_bytes()   # decode only: after the prefill
    toks, sst = spec125.generate(model, list(ids), cap, k_mtp=3, max_draft=3, lookup=0, prefill_chunk=512,
                                 prefilled=state, stop_ids=EOS)
    t2 = time.perf_counter()
    d1 = ext.defer_stats()                        # (rows, waited, late, over), cumulative; bt_b12's speed CLI reports these
    SSD.update(n=len(toks), passes=sst.get("passes"), reads=ext.stats()["misses"] - m0, waited=d1[1] - d0[1],
               late=d1[2] - d0[2], over=d1[3] - d0[3], rows=d1[0] - d0[0], disk_mb=round((diskread_bytes() - k0) / 1e6, 1),
               pf_s=round(t1 - t0, 3), dec_s=round(t2 - t1, 3), cm=B.CFG.get("cm"), aw=B.AW_N[0] - aw0,
               pfr=[list(x) for x in B.PFR_LOG[pf0:]] or None)
    toks = [int(x) for x in toks]
    for j, x in enumerate(toks):
        if x in EOS:
            return toks[:j + 1], "eos"
    return toks[:cap], "length"


def _gen_ref2(rt, ids, cap, sampler, seed):
    """R-40 REF2 (Leap's batch-invariant kernels, ~/Leap/scripts/ref2.py, applied at load): ref2.generate = its plain
    prefill, then each token as a 1-row verify step + commit keep 1 (ref2.ar_step), greedy, stopping at EOS"""
    assert sampler.temperature == 0.0, "the REF2 rows are greedy only"
    import ref2
    ref2.reset_counts()                           # per-path kernel calls (counted at graph build): proof REF2 engaged
    toks = [int(x) for x in ref2.generate(rt.model if hasattr(rt, "model") else rt, list(ids), cap, stop=EOS)]
    REF2.update(n=len(toks), calls=dict(ref2.counts()))
    for j, x in enumerate(toks):
        if x in EOS:
            return toks[:j + 1], "eos"
    return toks[:cap], "length"


REF2 = {}                                         # the last REF2 row's patch call counts, for its row


def _gen_fast24(rt, ids, cap, sampler, seed):
    """BigMoE's 24 GB fast mode as it ships (scripts/fast24.generate_fast24): spec125 MTP, fixed widths 3:3:0, greedy,
    stopping at EOS / <|im_end|> / <|endoftext|>"""
    assert sampler.temperature == 0.0, "the fast24 rows are greedy only"
    from fast24 import generate_fast24, _RT
    toks, _ = generate_fast24(rt, list(ids), cap)
    toks = [int(x) for x in toks]
    stop = EOS | set(_RT.get("stop", ()))
    for j, x in enumerate(toks):
        if x in stop:
            return toks[:j + 1], "eos"
    return toks[:cap], "length"


T0 = {}                                           # T0 (PREREG_t0): the arm's theta, and the last row's counts


def _gen_t0(rt, ids, cap, sampler, seed):
    """T0: Fit12's top-2 two-pass greedy decode at the arm's theta (t0_hook.gen); its counts go to the row"""
    import t0_hook
    toks, fin = t0_hook.gen(rt, ids, cap, sampler, seed, T0["theta"])
    T0["stats"] = dict(t0_hook.STATS)
    return toks, fin


def t0_gate(rt, sampler, log):
    """T0's VOID check: theta 1.01 on humaneval/HumanEval/156, 96 tokens, gives Fit12's gate logits-chain sha"""
    import t0_hook
    it = next(x for x in D.load("dec_humaneval") if x["key"] == "humaneval/HumanEval/156")
    t0_hook.gen(rt, it["prompt_ids"], 96, sampler, 0, 1.01)
    got = t0_hook.STATS.get("lsha")
    log(f"T0 gate: theta 1.01 on HumanEval/156 x96: lsha {got} (Fit12's G1: 37ccd09ba2)")
    if got != "37ccd09ba2":
        log("T0: VOID: the gate does not reproduce Fit12's exact AR decode")
        raise SystemExit(5)


def fast_decode_gate(rt, v, out, sampler, log):
    """plan variants: use the compiled decode tiers only if they equal the plain ones on data AND re-decoding an
    already-saved row (made by the plain path, possibly at another C) gives the same tokens"""
    if not v.get("plan"):
        return
    tiers = sorted({n for *_, n in M.STATE.segs if n < 4})              # every tier level of the plan (3 and 2)
    M.STATE.fast_decode = all(M.fast_tier_check(n) for n in tiers)
    log(f"fast decode tiers {tiers}: data check {'equal' if M.STATE.fast_decode else 'DIFFERENT -> plain path'}")
    rows = [json.loads(l) for l in open(out)] if os.path.exists(out) else []
    rows = [r for r in rows if not r.get("fast")]
    if not rows or not M.STATE.fast_decode:
        return
    r = min(rows, key=lambda r: len(r["completion_ids"]))
    ids = next(it for s in SETS + CARD for it in D.load("dec_" + s) if it["key"] == r["key"])["prompt_ids"]
    t = time.time()
    toks, _ = _gen(rt, ids, len(r["completion_ids"]), sampler, 0)
    same = toks == r["completion_ids"]
    log(f"fast decode tiers: re-decoded {r['key']} ({len(toks)} tokens, {len(toks) / (time.time() - t):.1f} tok/s): "
        f"{'identical' if same else 'DIFFERENT'} to the saved plain-path row")
    if not same:
        M.STATE.fast_decode = False
        toks, _ = _gen(rt, ids, len(r["completion_ids"]), sampler, 0)
        if toks != r["completion_ids"]:
            raise SystemExit("decode is not reproducible against the saved row even on the plain path: stopping")
        log("fast decode tiers: plain path reproduces the row; continuing on the plain path")


SSD = {}                                          # the last MTP row's decode-phase SSD counters (bt_b12's ext), for its row


def diskread_bytes():
    """bytes this process has read from disk (proc_pid_rusage ri_diskio_bytesread; F_NOCACHE expert reads included)"""
    import ctypes

    class RU(ctypes.Structure):                   # rusage_info_v4: uuid, then 64-bit counters
        _fields_ = [("uuid", ctypes.c_uint8 * 16)] + [(f"u{i}", ctypes.c_uint64) for i in range(40)]
    ru = RU()
    return ru.u16 if ctypes.CDLL(None).proc_pid_rusage(os.getpid(), 4, ctypes.byref(ru)) == 0 else 0


class _RU(ctypes.Structure):                       # rusage_info_v4: uuid, then 64-bit counters
    _fields_ = [("uuid", ctypes.c_uint8 * 16)] + [(f"u{i}", ctypes.c_uint64) for i in range(40)]


def footprint_now_gb():
    """this process's current physical footprint (ri_phys_footprint), GB"""
    ru = _RU()
    return ru.u7 / 1e9 if ctypes.CDLL(None).proc_pid_rusage(os.getpid(), 4, ctypes.byref(ru)) == 0 else float("nan")


class RowMem:
    """per-row memory and pause record: a sampler thread reads the current footprint every 25 ms (max since the row
    began), counts time with the quiet-window PAUSE file present, and time this process was frozen (a SIGSTOP from a
    heat pause or soft_end's ramp shows as a gap in the sampler's own clock); rows with either are not timed fairly"""
    PAUSE = os.path.expanduser("~/.local/share/quiet/PAUSE")

    def __init__(self, dt=0.025):
        import threading
        self.dt, self.max, self.paused, self.frozen, self.t0 = dt, 0.0, 0.0, 0.0, 0.0
        threading.Thread(target=self._run, daemon=True).start()

    def _run(self):
        last = time.monotonic()
        while True:
            f = footprint_now_gb()
            if f > self.max:
                self.max = f
            now = time.monotonic()
            if now - last > 0.5:                       # frozen (or starved) for the gap
                self.frozen += now - last
            if os.path.exists(self.PAUSE):
                self.paused += now - last
            last = now
            time.sleep(self.dt)

    def start(self):
        self.max, self.paused, self.frozen = footprint_now_gb(), 0.0, 0.0
        self.t0 = self.max
        return self

    def row(self):
        now = footprint_now_gb()
        return dict(start=round(self.t0, 3), end=round(now, 3), max=round(max(self.max, now), 3),
                    life=round(footprint_peak_gb(), 3), paused_s=round(self.paused, 1), frozen_s=round(self.frozen, 1))


def footprint_peak_gb():
    """this process's lifetime peak physical footprint (proc_pid_rusage ri_lifetime_max_phys_footprint: what Activity
    Monitor calls Memory; it counts MLX's GPU buffers, which RSS misses), GB"""
    import ctypes

    class RU(ctypes.Structure):                   # rusage_info_v4: uuid, then 64-bit counters
        _fields_ = [("uuid", ctypes.c_uint8 * 16)] + [(f"u{i}", ctypes.c_uint64) for i in range(40)]
    ru = RU()
    if ctypes.CDLL(None).proc_pid_rusage(os.getpid(), 4, ctypes.byref(ru)) != 0:
        return float("nan")
    return ru.u28 / 1e9


def run(rt, v, thinking=False, sets=SETS, log=print, gate=None, limit=0, max_rows=0, chunk_s=0, keys=None):
    """gate: the streamer's spin gate; checked before each row is saved (a timed-out gate, e.g. a process frozen
    mid-pass by the thermostat, invalidates what follows: the stage stops and the next chunk redoes the row).
    max_rows: decode at most this many new rows in this process, then return "chunk" (a runner's chunk of <= 15 min,
    RULES 'Long runs share the queue'); the chunk's provenance and footprint go to results/<V>/chunks.jsonl.
    chunk_s: the same by time: start no new row once this many seconds have passed (rows of unknown speed)
    keys: only these items (a verdict's follow-up rows, e.g. the rows where two arms differ)"""
    from mtplx.sampling import SamplerConfig
    M.configure(v, prefill=False)
    out = path(v["name"], thinking)
    os.makedirs(os.path.dirname(out), exist_ok=True)
    done = {json.loads(l)["key"] for l in open(out)} if os.path.exists(out) else set()
    tok = rt.tokenizer
    sampler = (SamplerConfig(temperature=0.6, top_p=0.95, top_k=20) if thinking
               else SamplerConfig(temperature=0.0, top_p=1.0, top_k=0))
    eos = EOS
    if not thinking:
        fast_decode_gate(rt, v, out, sampler, log)
    if v.get("t0") is not None:
        T0["theta"] = v["t0"]
        t0_gate(rt, sampler, log)
    t0, ntok, nrow, mem, ended = time.time(), 0, 0, RowMem(), None
    with open(out, "a") as f:
        for s in sets:
            if ended:
                break
            for n_it, it in enumerate(D.load("dec_" + s)):
                if limit and n_it >= limit:              # a check on the first rows of each set
                    break
                if it["key"] in done or (keys is not None and it["key"] not in keys):
                    continue
                if (max_rows and nrow >= max_rows) or (chunk_s and nrow and time.time() - t0 > chunk_s):
                    ended = "chunk"
                    break
                if thinking:
                    ids = tok.apply_chat_template([{"role": "user", "content": it["user"]}], add_generation_prompt=True,
                                                  enable_thinking=True)
                    ids = list(ids if isinstance(ids[0], int) else ids["input_ids"])
                    cap = THINK_CAP[s]
                else:
                    ids, cap = it["prompt_ids"], it["max_tokens"]
                seed = int(hashlib.sha1(it["key"].encode()).hexdigest()[:8], 16)
                t = time.time()
                mem.start()
                gen = (_gen_t0 if v.get("t0") is not None else _gen_fast24 if v.get("fast24") else _gen_mtp if v.get("mtp")
                       else _gen_ref2 if v.get("ref2") else _gen)
                toks, finish = gen(rt, ids, cap, sampler, seed)
                if gate is not None:
                    gate.check()
                ntok += len(toks)
                nrow += 1
                row = dict(key=it["key"], set=s, n_prompt=len(ids), completion_ids=toks, finish=finish,
                           text=tok.decode([x for x in toks if x not in eos]), seconds=round(time.time() - t, 2),
                           fast=bool(M.STATE.fast_decode), mem=mem.row())
                if T0.get("stats"):                      # T0 rows: steps, pass-2 rows, rate, logits-chain sha, times
                    row["t0"] = T0.pop("stats")
                if SSD:                                  # MTP rows: decode-phase SSD expert reads (misses), waited, late
                    row["ssd"] = dict(SSD)
                    SSD.clear()
                if REF2:
                    of = {"tier_nax_ooo": ("nax6", "nax6_ooo")}   # NAX6 (PREREG_nax6): its calls count under these
                    off = [k for k, x in v.get("ref2_cfg", {}).items()
                           if x is True and not any(REF2["calls"].get(c) for c in of.get(k, (k,)))]
                    assert len(toks) < 2 or not off, f"{it['key']}: REF2 switches {off} never ran ({REF2['calls']})"   # REF2c:
                    #                                      every token after the first is a 16-row AR step, so both count
                    row["ref2"] = dict(REF2)
                    REF2.clear()
                f.write(json.dumps(row, ensure_ascii=False) + "\n")
                f.flush()
                ssd = f", SSD reads {row['ssd']['reads'] / max(1, row['ssd']['n']):.1f}/token" if "ssd" in row else ""
                log(f"{v['name']} {it['key']}: {len(toks)} tokens {finish} ({ntok / (time.time() - t0):.1f} tok/s overall{ssd})")
                flag = os.environ.get("EVALSUITE_YIELD_FLAG")
                if flag and os.path.exists(flag):         # a [low] stage gives way to research at a row boundary
                    log(f"{v['name']}: a research ticket waits: yielding after this row")
                    return "yield"
    if ended:
        log(f"{v['name']}: chunk of {nrow} rows done")
    if max_rows or chunk_s:
        with open(os.path.join(os.path.dirname(out), "chunks.jsonl"), "a") as cf:
            cf.write(json.dumps(dict(rows=nrow, seconds=round(time.time() - t0, 1), footprint_peak_gb=footprint_peak_gb(),
                                     provenance=env.provenance(), finished=time.time())) + "\n")
    log(f"{v['name']}: peak physical footprint {footprint_peak_gb():.2f} GB")
    pr1 = getattr(sys.modules.get("fit_pr1"), "CALLS", [None])[0]   # Fit12's PR1: patched keep-1 replays (None: not loaded)
    if pr1 is not None:
        log(f"{v['name']}: PR1 2-row replays this process: {pr1}")
    json.dump(dict(variant=v, thinking=thinking, provenance=env.provenance(), finished=time.time(), stats=M.STATE.stats,
                   footprint_peak_gb=footprint_peak_gb(), limit=limit, pr1_calls=pr1),
              open(os.path.join(os.path.dirname(out), "decode_think.json" if thinking else "decode.json"), "w"), indent=1)
    return ended
